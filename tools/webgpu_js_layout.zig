//! Emits web/zigote_webgpu_layout.js: the wasm32 field offsets of the webgpu.h structs and the
//! value → tag tables of its enums, reflected out of the Zig binding (libraries/wgpu). The JS
//! WebGPU implementation (web/zigote_webgpu.js) reads engine memory through these instead of
//! hand-copied offsets, so the two cannot drift. Must be compiled FOR wasm32 — offsets are
//! pointer-width dependent:
//!
//!   zig build-exe -fno-entry -rdynamic -target wasm32-freestanding -O ReleaseSmall \
//!       --dep wgpu -Mroot=tools/webgpu_js_layout.zig -Mwgpu=libraries/wgpu/root.zig
//!   node -e "WebAssembly.instantiate(require('fs').readFileSync('root.wasm')).then(({instance: i}) =>
//!       process.stdout.write(Buffer.from(i.exports.memory.buffer, i.exports.layout_ptr(), i.exports.layout_len())))" \
//!       > web/zigote_webgpu_layout.js
const std = @import("std");
const wgpu = @import("wgpu");

const structs = .{
    "StringView",                 "ChainedStruct",              "RequestAdapterOptions",
    "RequestAdapterCallbackInfo", "AdapterInfo",                "DeviceDescriptor",
    "RequestDeviceCallbackInfo",  "UncapturedErrorCallbackInfo", "DeviceLostCallbackInfo",
    "Limits",                     "BufferDescriptor",           "BufferMapCallbackInfo",
    "TextureDescriptor",          "Extent3D",                   "Origin3D",
    "TextureViewDescriptor",      "SamplerDescriptor",          "BindGroupLayoutDescriptor",
    "BindGroupLayoutEntry",       "BufferBindingLayout",        "SamplerBindingLayout",
    "TextureBindingLayout",       "StorageTextureBindingLayout", "BindGroupDescriptor",
    "BindGroupEntry",             "PipelineLayoutDescriptor",   "ShaderModuleDescriptor",
    "ShaderSourceWGSL",           "ConstantEntry",              "ProgrammableStageDescriptor",
    "ComputePipelineDescriptor",  "RenderPipelineDescriptor",   "VertexState",
    "VertexBufferLayout",         "VertexAttribute",            "PrimitiveState",
    "DepthStencilState",          "StencilFaceState",           "MultisampleState",
    "FragmentState",              "ColorTargetState",           "BlendState",
    "BlendComponent",             "CommandEncoderDescriptor",   "CommandBufferDescriptor",
    "RenderPassDescriptor",       "ColorAttachment",            "DepthStencilAttachment",
    "Color",                      "ComputePassDescriptor",      "TexelCopyTextureInfo",
    "TexelCopyBufferInfo",        "TexelCopyBufferLayout",      "SurfaceDescriptor",
    "EmscriptenSurfaceSourceCanvasHTMLSelector", "SurfaceConfiguration", "SurfaceCapabilities",
    "SurfaceTexture",             "EnumerateAdapterOptions",
};

const enums = .{
    "TextureFormat",         "TextureDimension",   "ViewDimension",       "TextureAspect",
    "SampleType",            "StorageTextureAccess", "BufferBindingType", "SamplerBindingType",
    "AddressMode",           "FilterMode",         "MipmapFilterMode",    "CompareFunction",
    "VertexFormat",          "VertexStepMode",     "PrimitiveTopology",   "IndexFormat",
    "FrontFace",             "CullMode",           "StencilOperation",    "BlendOperation",
    "BlendFactor",           "LoadOp",             "StoreOp",             "CompositeAlphaMode",
    "PresentMode",           "FeatureName",        "PowerPreference",     "SType",
    "OptionalBool",          "BackendType",        "AdapterType",
};

fn generate() []const u8 {
    @setEvalBranchQuota(1_000_000);
    const p = std.fmt.comptimePrint;
    var out: []const u8 = "// GENERATED by tools/webgpu_js_layout.zig — do not edit.\n" ++
        "// wasm32 layout of the webgpu.h structs and enums in libraries/wgpu.\n" ++
        "mergeInto(LibraryManager.library, {\n  $WGPU_LAYOUT: {\n    S: {\n";
    for (structs) |name| {
        const T = @field(wgpu, name);
        out = out ++ p("      {s}: {{ __size: {d}", .{ name, @sizeOf(T) });
        for (@typeInfo(T).@"struct".field_names) |f| out = out ++ p(", {s}: {d}", .{ f, @offsetOf(T, f) });
        out = out ++ " },\n";
    }
    out = out ++ "    },\n    E: {\n";
    for (enums) |name| {
        const info = @typeInfo(@field(wgpu, name)).@"enum";
        out = out ++ p("      {s}: {{", .{name});
        for (info.field_names, info.field_values) |n, v| out = out ++ p(" {d}: '{s}',", .{ v, n });
        out = out ++ " },\n";
    }
    return out ++ "    },\n  },\n});\n";
}

const text = generate();

/// The host reads the generated text straight out of linear memory (see the module doc).
export fn layout_ptr() [*]const u8 {
    return text.ptr;
}
export fn layout_len() usize {
    return text.len;
}
